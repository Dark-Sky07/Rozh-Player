const dicts: Record<Lang, Dict> = { fa, en };

export function currentLang(): Lang {
  return store.settings.lang;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const lang = currentLang();
  const raw = dicts[lang][key] ?? dicts.en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

/** Number formatting that respects the active language (Persian digits in fa). */
export function n(value: number | string): string {
  const s = String(value);
  if (currentLang() !== 'fa') return s;
  const map = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  return s.replace(/\d/g, (d) => map[Number(d)]);
}
